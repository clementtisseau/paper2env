"""Inspect AI task: run a paper's rediscovery environment with an API model.

One sample per hint level (times epochs). The agent works in a Docker sandbox
holding the paper's starter repository (no network, CPU only) and must leave
the paper's SUBMISSION and REPORT files in /workspace. Scorers: one per entry
of the paper's GRADERS (run in its grader image, submission read-only, no
network), plus the paper's LLM judge (grader/judge.md) if judge models are
given.

    inspect eval core/task.py --model <agent model> -T paper=score-centering \
        -T levels=L3,L4 -T experiments=true -T judges=<judge model> -T hours=2 -T epochs=3

epochs: attempts per level (pass@k). judges: one or more judge models (none:
no judge). On a network that intercepts TLS, set P2E_PIPCA=<CA bundle> so the
images build. The other options are in paper_env's docstring.
"""
import asyncio
import json
import sys
from pathlib import Path

from inspect_ai import Task, task
from inspect_ai.agent import react
from inspect_ai.dataset import MemoryDataset, Sample
from inspect_ai.model import CompactionAuto, get_model
from inspect_ai.scorer import Score, Target, mean, scorer
from inspect_ai.solver import TaskState
from inspect_ai.tool import bash, python, text_editor
from inspect_ai.util import sandbox

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import compose as prompts  # noqa: E402
import grade as grade_lib  # noqa: E402
import judge as judge_lib  # noqa: E402
import paper as papers  # noqa: E402
from images import WORKSPACE, ensure_images  # noqa: E402

COMPOSE = """# Generated by core/task.py: Inspect sandbox for the {paper} {starter} starter.
services:
  default:
    image: {image}
    init: true
    command: tail -f /dev/null
    working_dir: /workspace
    network_mode: none
    cpus: {cpus}
    mem_limit: 8g
"""


def prepare(paper, experiments, cpus, rebuild=False):
    """Generate the starter, build the images and write the sandbox compose
    file. Returns (starter name, compose file)."""
    starter, tag = ensure_images(paper, experiments, rebuild)
    path = paper.DIR / "docker/generated" / f"compose.{starter}.yaml"
    path.parent.mkdir(exist_ok=True)
    path.write_text(COMPOSE.format(paper=paper.NAME, starter=starter, image=tag, cpus=cpus))
    return starter, path


# ------------------------------------------------------------------ submission
async def read_submission(paper, state):
    """The submission and the report (empty if missing), and the submission's
    diff against the starter."""
    sb = sandbox()
    async def read(name):
        try:
            return await sb.read_file(f"{WORKSPACE}/{name}")
        except Exception:
            return ""
    submission, report = await read(paper.SUBMISSION), await read(paper.REPORT)
    return submission, report, grade_lib.diff(paper, state.metadata["experiments"], submission)


# ------------------------------------------------------------------ scorers
def grader_scorer(paper, grader):
    """Score 1 if the grader script reports the submission correct; its full
    output goes in the metadata."""
    @scorer(metrics=[mean()], name=grader["name"])
    def make():
        async def score(state: TaskState, target: Target):
            submission, _, _ = await read_submission(paper, state)
            if not submission:
                return Score(value=0, explanation=f"no {paper.SUBMISSION}")
            result = await asyncio.to_thread(grade_lib.run_grader, paper, submission, grader["args"],
                                             grader["timeout"])
            return Score(value=int(bool(result.get("correct"))), explanation=json.dumps(result)[:4000],
                         metadata=result)
        return score
    return make()


@scorer(metrics=[mean()])
def judge(paper, models):
    """Score 1 if a majority of the judge models find the paper's idea in the
    submission (core/judge.py). An invalid answer is asked again once."""
    async def score(state: TaskState, target: Target):
        submission, _, diff = await read_submission(paper, state)
        if not submission:
            return Score(value=0, explanation=f"no {paper.SUBMISSION}")
        prompt = judge_lib.build_prompt(paper, diff, submission)
        answers, errors = [], []
        for name in models:
            for _ in range(2):
                try:
                    out = await get_model(name).generate(prompt)
                    answers.append(judge_lib.validate(judge_lib.parse(out.completion), paper.JUDGE_LABELS))
                    break
                except Exception as e:
                    errors.append(f"{name}: {type(e).__name__}: {e}"[:300])
        if not answers:
            return Score(value=0, explanation="no valid judge answer: " + "; ".join(errors))
        verdict = judge_lib.majority(answers)
        return Score(value=int(verdict["idea_found"]), explanation=json.dumps(verdict),
                     metadata={"verdict": verdict, "answers": answers, "errors": errors})
    return score


# ------------------------------------------------------------------ task
@task
def paper_env(paper="score-centering", levels="", experiments=True, judges="", hours=2.0, tokens=5_000_000,
                    messages=500, compaction=True, cpus=4, epochs=1, rebuild=False):
    """One run per level of the paper (default: its DEFAULT_LEVELS), times epochs. A run ends when the agent calls
    submit() or hits a limit:
      hours     working time (time spent waiting on the model API not counted);
                wall-clock time is capped at 3x that as a safety net
      tokens    total tokens over the run (input + output), the cost bound
      messages  total messages, a guard against loops
    compaction: summarize or compact the history near the context limit
    (native compaction when the provider has it, else a summary).
    experiments: whether the agent can run training (run_dev.sh, dev/mini.py);
    the starter and the tools section of the prompt follow it."""
    paper = papers.load(paper)
    levels = [l.strip() for l in str(levels).split(",") if l.strip()] or list(paper.DEFAULT_LEVELS)
    judges = [j.strip() for j in str(judges).split(",") if j.strip()]
    flag = lambda v: str(v).lower() not in ("false", "0", "no")
    experiments = flag(experiments)
    starter, compose_file = prepare(paper, experiments, cpus, rebuild=bool(rebuild))
    samples = []
    for level in levels:
        text = prompts.compose(paper, level, cpus=cpus, hours=hours, experiments=experiments)
        samples.append(Sample(id=f"{paper.NAME}-{starter}-{level}", input=text,
                              metadata={"paper": paper.NAME, "level": level, "starter": starter, "experiments": experiments,
                                        "prompt": text},
                              sandbox=("docker", str(compose_file))))
    scorers = [grader_scorer(paper, g) for g in paper.GRADERS] + ([judge(paper, judges)] if judges else [])
    agent = react(
        prompt=("You are a machine learning researcher. Work in /workspace with the tools you have. "
                f"When {paper.SUBMISSION} and {paper.REPORT} are final, call submit() with a one-line summary."),
        tools=[bash(timeout=3600), python(timeout=3600), text_editor()],
        compaction=CompactionAuto() if flag(compaction) else None,
    )
    seconds = int(float(hours) * 3600)
    return Task(dataset=MemoryDataset(samples), solver=agent, scorer=scorers, epochs=int(epochs),
                working_limit=seconds, time_limit=3 * seconds,
                token_limit=int(tokens) if tokens else None,
                message_limit=int(messages) if messages else None)
